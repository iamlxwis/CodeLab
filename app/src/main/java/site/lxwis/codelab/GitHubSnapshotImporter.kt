package site.lxwis.codelab

import java.io.ByteArrayInputStream
import java.io.ByteArrayOutputStream
import java.io.IOException
import java.net.HttpURLConnection
import java.net.URI
import java.net.URL
import java.util.zip.ZipInputStream
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

/** Public GitHub source snapshot import. This is explicitly NOT a Git clone. */
internal object GitHubSnapshotImporter {
    private const val MAX_COMPRESSED = 17 * 1024 * 1024
    private const val MAX_EXPANDED = 16 * 1024 * 1024
    private const val MAX_FILE = 256 * 1024
    private const val MAX_ENTRIES = 1024

    fun canonicalSlug(input: String): String {
        val slug = input.trim().removePrefix("https://github.com/")
            .removeSuffix("/").removeSuffix(".git")
        require(slug.matches(Regex("[A-Za-z0-9_.-]{1,70}/[A-Za-z0-9_.-]{1,100}")) &&
            slug.split("/").none { it == "." || it == ".." }) {
            "Enter a public GitHub owner/repository, for example: eclipse/jgit"
        }
        return slug
    }

    private fun openSafeUrl(target: String): HttpURLConnection {
        val uri = URI(target)
        require(uri.scheme == "https" && uri.port == -1 &&
            uri.userInfo == null && uri.query == null &&
            uri.host in setOf("api.github.com", "codeload.github.com")) {
            "Unexpected repository download address."
        }
        return (URL(target).openConnection() as HttpURLConnection).apply {
            instanceFollowRedirects = false
            connectTimeout = 20000
            readTimeout = 20000
            setRequestProperty("User-Agent", "CodeLab-Android/0.2")
            setRequestProperty("Accept", "application/vnd.github+json")
        }
    }

    fun downloadPublicArchive(slug: String): ByteArray {
        val canonical = canonicalSlug(slug)
        var address = "https://api.github.com/repos/" + canonical + "/zipball"
        for (redirect in 0..4) {
            val connection = openSafeUrl(address)
            try {
                val status = connection.responseCode
                if (status in 300..399) {
                    val location = connection.getHeaderField("Location")
                        ?: throw IOException("GitHub did not provide a download location.")
                    address = URI(address).resolve(location).toString()
                    continue
                }
                if (status == 404) throw IOException("Public GitHub repository not found.")
                if (status == 403) throw IOException("GitHub public download rate limit reached.")
                if (status != 200) throw IOException("GitHub archive request failed: HTTP " + status)
                val bytes = ByteArrayOutputStream()
                connection.inputStream.use { source ->
                    val buffer = ByteArray(8192)
                    var total = 0
                    while (true) {
                        val n = source.read(buffer)
                        if (n < 0) break
                        total += n
                        if (total > MAX_COMPRESSED) throw IOException("Repository ZIP exceeds 17 MiB.")
                        bytes.write(buffer, 0, n)
                    }
                }
                return bytes.toByteArray()
            } finally {
                connection.disconnect()
            }
        }
        throw IOException("Too many GitHub download redirects.")
    }

    /** Removes GitHub's autogenerated leading directory and enforces zip-bomb limits. */
    fun normalizeArchive(archive: ByteArray): ByteArray {
        val bytes = ByteArrayOutputStream()
        var total = 0
        var count = 0
        var prefix: String? = null
        ZipOutputStream(bytes).use { output ->
            ZipInputStream(ByteArrayInputStream(archive)).use { zip ->
                while (true) {
                    val item = zip.nextEntry ?: break
                    count++
                    if (count > MAX_ENTRIES) throw IOException("Repository has too many files.")
                    val raw = item.name
                    if (raw.startsWith("/") || raw.contains('\\') || raw.contains("../"))
                        throw IOException("Unsafe repository archive path.")
                    val parent = raw.substringBefore('/')
                    if (prefix == null) prefix = parent
                    if (prefix != parent) throw IOException("Unexpected GitHub archive layout.")
                    val relative = raw.substringAfter('/', "").trimEnd('/')
                    if (relative.isNotBlank()) {
                        val segments = relative.split('/')
                        if (segments.any { it.isBlank() || it == "." || it == ".." })
                            throw IOException("Invalid archive path.")
                        val name = if (item.isDirectory) relative + "/" else relative
                        output.putNextEntry(ZipEntry(name))
                        if (!item.isDirectory) {
                            val block = ByteArray(8192)
                            var current = 0
                            while (true) {
                                val n = zip.read(block)
                                if (n < 0) break
                                total += n
                                current += n
                                if (current > MAX_FILE || total > MAX_EXPANDED)
                                    throw IOException("Source file exceeds the supported project size.")
                                output.write(block, 0, n)
                            }
                        }
                        output.closeEntry()
                    }
                    zip.closeEntry()
                }
            }
        }
        return bytes.toByteArray()
    }

    fun importPublic(store: ProjectStore, slug: String, projectName: String) {
        val archive = downloadPublicArchive(slug)
        store.importZip(projectName, ByteArrayInputStream(normalizeArchive(archive)))
    }
}
